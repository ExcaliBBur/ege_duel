def s1_concepts(r):
    concept, members, outsiders = r.choice(CONCEPTS)
    options = [(term, False) for term in r.sample(members, 4)] + [(term, True) for term in r.sample(outsiders, 2)]
    r.shuffle(options)
    lines = "\n".join(f"{index}) {term}" for index, (term, _) in enumerate(options, start=1))
    made = task(
        f"Ниже приведён перечень терминов. Все они, за исключением двух, относятся к понятию «{concept}». Найдите два термина, «выпадающих» из общего ряда, "
        f"и запишите цифры, под которыми они указаны.\n\n{lines}",
        "".join(str(index) for index, (_, odd) in enumerate(options, start=1) if odd),
        f"К понятию «{concept}» не относятся: " + ", ".join(term for term, odd in options if odd) + ".")
    made["kind"] = "set"
    return made


