def statements_generator(name, intro, pool):
    def generator(r):
        texts, flags = pick_statements(r, pool)
        return choose(intro, texts, flags, "Верные суждения: " + " ".join(text for text, flag in zip(texts, flags) if flag))
    generator.__name__ = name
    return generator


def cases_generator(name, cases):
    """Ситуация и список вариантов: нужно выбрать все подходящие."""
    def generator(r):
        situation, right, wrong, explanation = r.choice(cases)
        count = r.choice([2, 3])
        options = [(text, True) for text in r.sample(right, min(count, len(right)))]
        options += [(text, False) for text in r.sample(wrong, 5 - len(options))]
        r.shuffle(options)
        return choose(situation, [text for text, _ in options], [flag for _, flag in options], explanation)
    generator.__name__ = name
    return generator


def categories_generator(name, tables):
    """Соответствие «пример -> понятие»: пять примеров, цифры в ответе могут повторяться."""
    def generator(r):
        relation, groups = r.choice(tables)
        names = r.sample(sorted(groups), min(len(groups), r.choice([3, 4])))
        while True:
            items = r.sample([(example, group) for group in names for example in groups[group]], 5)
            if len({group for _, group in items}) >= 2:
                break
        made = matching(
            f"Установите соответствие между {relation}: к каждой позиции, данной в первом столбце, подберите соответствующую позицию из второго столбца. "
            "Цифры в ответе могут повторяться.",
            [example for example, _ in items], names,
            "".join(str(names.index(group) + 1) for _, group in items),
            "; ".join(f"{example}: {group}" for example, group in items) + ".")
        return made
    generator.__name__ = name
    return generator


