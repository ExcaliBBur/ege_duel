def g_resources(r):
    resource, unit, small = r.choice([("нефти", "млрд т", "млн т"), ("природного газа", "трлн м³", "млрд м³"), ("каменного угля", "млрд т", "млн т")])
    while True:
        reserves = r.choice([Fraction(3, 2), 2, 4, 5, 8, 12, 16, 30, 48])
        production = r.choice([50, 80, 100, 125, 160, 200, 250, 400, 500])
        years = Fraction(reserves) * 1000 / production
        if years.denominator == 1 and 15 <= years <= 300:
            break
    return task(
        f"Разведанные запасы {resource} в стране составляют {dec(reserves)} {unit}, а ежегодная добыча равна {production} {small}. "
        "Определите ресурсообеспеченность страны этим видом ресурсов: на сколько лет хватит запасов при сохранении такого уровня добычи?",
        dec(years),
        f"Ресурсообеспеченность равна отношению запасов к годовой добыче: {dec(Fraction(reserves) * 1000)} {small} : {production} {small} = {dec(years)} лет.",
    )


def g_migration(r):
    population = r.choice([850, 1200, 1500, 2400, 3600]) * 1000
    natural = r.choice([-9, -6, -4, -2, 3, 5]) * 1000 + r.choice([0, 200, 500])
    migration = r.choice([-7, -3, 2, 4, 6, 11]) * 1000 + r.choice([0, 300, 700])
    final = population + natural + migration
    return task(
        f"Численность населения области на начало года составляла {population} человек, а на конец года {final} человек. "
        + (f"Естественный прирост за год составил {natural} человек." if natural > 0 else f"Естественная убыль населения за год составила {-natural} человек.")
        + " Определите величину миграционного прироста населения области за год. "
        "Ответ дайте в человеках (если население за счёт миграции уменьшилось, запишите число со знаком минус).",
        dec(migration),
        f"Общий прирост равен {final} - {population} = {final - population} человек. Миграционный прирост равен общему минус естественный: "
        f"{final - population} - ({natural}) = {migration} человек.",
    )


def g_longitude(r):
    hours = r.choice([-9, -8, -6, -5, -4, -3, -2, 2, 3, 4, 5, 6, 8, 9, 10])
    minutes = r.choice([0, 20, 40])
    noon_gmt = 12 * 60 - (hours * 60 + (minutes if hours > 0 else -minutes))
    degrees = abs(hours) * 15 + minutes // 4
    side = "восточной" if hours > 0 else "западной"
    return task(
        f"В пункте А полдень по местному солнечному времени наступает тогда, когда на Гринвичском меридиане {noon_gmt // 60} ч {noon_gmt % 60:02d} мин. "
        "Определите географическую долготу пункта А. В ответе запишите число градусов (восточную долготу без знака, западную со знаком минус).",
        dec(degrees if hours > 0 else -degrees),
        f"Разница с гринвичским полуднем составляет {abs(hours)} ч {minutes:02d} мин. Земля поворачивается на 15° за час и на 1° за 4 минуты: "
        f"{abs(hours)}·15 + {minutes} : 4 = {degrees}° {side} долготы (полдень наступает {'раньше' if hours > 0 else 'позже'}, чем в Гринвиче).",
    )


