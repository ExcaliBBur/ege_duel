def property_generator(name, table, exact=None):
    """Выбор веществ с заданным свойством. exact: ровно столько верных ответов, иначе два или три."""
    def generator(r):
        question, fits, others, explanation = r.choice(table)
        count = exact or r.choice([2, 3])
        right = r.sample(fits, count)
        options = right + r.sample(others, 5 - count)
        r.shuffle(options)
        ask = "выберите два вещества" if exact == 2 else "выберите все вещества"
        return digits(task(f"Из предложенного перечня {ask}, которые {question}. Запишите номера выбранных веществ.\n\n{numbered(options)}",
                           "".join(str(index + 1) for index, option in enumerate(options) if option in right), explanation), "set")
    generator.__name__ = name
    return generator


