def p26_solution(r):
    kind = r.choice(["water", "mix", "evaporate", "add"])
    mass, share = r.choice([100, 120, 150, 200, 250, 300, 400]), r.choice([5, 8, 10, 12, 15, 20, 25])
    salt = Fraction(mass * share, 100)
    tail = " Ответ дайте в процентах с точностью до десятых."
    if kind == "water":
        water = r.choice([20, 30, 50, 80, 100, 150])
        return task(f"К {mass} г раствора соли с массовой долей {share}% добавили {water} г воды. Вычислите массовую долю соли в полученном растворе." + tail,
                    tenths(salt / (mass + water) * 100), f"Масса соли {dec(salt)} г, масса раствора {mass + water} г: {dec(salt)} : {mass + water} · 100% = {tenths(salt / (mass + water) * 100)}%.")
    if kind == "mix":
        second_mass, second_share = r.choice([50, 80, 100, 150, 200]), r.choice([30, 35, 40])
        total_salt = salt + Fraction(second_mass * second_share, 100)
        return task(f"Смешали {mass} г раствора с массовой долей соли {share}% и {second_mass} г раствора этой же соли с массовой долей {second_share}%. "
                    "Вычислите массовую долю соли в полученном растворе." + tail,
                    tenths(total_salt / (mass + second_mass) * 100),
                    f"Масса соли {dec(total_salt)} г, масса раствора {mass + second_mass} г: массовая доля {tenths(total_salt / (mass + second_mass) * 100)}%.")
    if kind == "evaporate":
        water = r.choice([20, 30, 40, 50])
        return task(f"Из {mass} г раствора соли с массовой долей {share}% выпарили {water} г воды. Вычислите массовую долю соли в полученном растворе." + tail,
                    tenths(salt / (mass - water) * 100), f"Масса соли {dec(salt)} г, масса раствора {mass - water} г: массовая доля {tenths(salt / (mass - water) * 100)}%.")
    added = r.choice([5, 10, 15, 20, 25])
    return task(f"К {mass} г раствора соли с массовой долей {share}% добавили {added} г этой же соли. Вычислите массовую долю соли в полученном растворе." + tail,
                tenths((salt + added) / (mass + added) * 100),
                f"Масса соли {dec(salt + added)} г, масса раствора {mass + added} г: массовая доля {tenths((salt + added) / (mass + added) * 100)}%.")


