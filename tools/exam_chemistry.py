        asked = r.sample(sorted(REACTIVITY), 4)
        # Реагент не должен совпадать с одним из веществ левого столбца.
        available = [sorted(reagent for reagent in REACTIVITY[substance][0] if not any(same(other, reagent) for other in asked)) for substance in asked]
        if any(len(reagents) < 3 for reagents in available):
            continue
