def one_pair(r, value_of, pool, wanted=None):
    """Пять элементов, среди которых ровно два имеют одинаковое значение признака (при wanted именно это значение)."""
    while True:
        picked = r.sample(pool, 5)
        values = [value_of(symbol) for symbol in picked]
        pairs = [(i, j) for i in range(5) for j in range(i + 1, 5) if values[i] is not None and values[i] == values[j]]
        if len(pairs) == 1 and (wanted is None or values[pairs[0][0]] == wanted):
            return picked, pairs[0]


