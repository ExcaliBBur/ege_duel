        extra = r.sample([reagent for reagent in ALL_REAGENTS if not any(same(other, reagent) for other in asked)], 3)
        rows = triples + [extra]
        # Каждому веществу должен подходить только свой набор: в чужих наборах есть реагент, с которым оно точно не реагирует.
