def exact(text, answers, explanation):
    made = task(text, answers[0], explanation)
    made["answers"] = list(answers)
    made["kind"] = "exact"
    return made


def numbered(options):
    return "\n".join(f"{index}) {option}" for index, option in enumerate(options, start=1))


def three_of_six(name, table):
    def generator(r):
        question, fits, others = r.choice(table)
        right = r.sample(fits, 3)
        options = right + r.sample(others, 3)
        r.shuffle(options)
        made = task(f"{question} Выберите три верных ответа из шести и запишите цифры, под которыми они указаны.\n\n{numbered(options)}",
                    "".join(str(index + 1) for index, option in enumerate(options) if option in right),
                    "Верные ответы: " + "; ".join(option for option in options if option in right) + ".")
        made["kind"] = "set"
        return made
    generator.__name__ = name
    return generator


def sequence_generator(name, table):
    def generator(r):
        instruction, steps = r.choice(table)
        shown = steps[:]
        while shown == steps:
            r.shuffle(shown)
        made = task(f"{instruction} Запишите соответствующую последовательность цифр.\n\n{numbered(shown)}",
                    "".join(str(shown.index(step) + 1) for step in steps), "Правильный порядок: " + "; ".join(steps) + ".")
        made["kind"] = "order"
        return made
    generator.__name__ = name
    return generator


def term_generator(name, table, lead):
    def generator(r):
        description, answers = r.choice(table)
        return exact(f"{lead} {description} Запишите ответ одним словом или словосочетанием.", answers, f"Это {answers[0]}.")
    generator.__name__ = name
    return generator


