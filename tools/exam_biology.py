    temperatures = list(range(10, 56, 5))
    top = r.randint(66, 95)
    # Скорость строго падает по мере удаления от оптимума, поэтому все утверждения проверяются однозначно.
    rates = [top - 2 * distance * (distance + 1) + r.choice([0, 1]) for distance in (abs(temperature - peak) // 5 for temperature in temperatures)]
    rates[temperatures.index(peak)] = top + 1
    rows = [["Температура, °C"] + [str(t) for t in temperatures], ["Скорость, усл. ед."] + [str(rate) for rate in rates]]
    low, other = r.sample([t for t in temperatures if t != peak], 2)
    wrong_peak = r.choice([t for t in temperatures if t != peak])
    first, second = sorted(r.sample(temperatures, 2))
    rising = all(rates[i] < rates[i + 1] for i in range(temperatures.index(first), temperatures.index(second)))
    pool = [
        [(f"Наибольшая скорость реакции наблюдалась при температуре {peak} °C.", True), (f"Наибольшая скорость реакции наблюдалась при температуре {wrong_peak} °C.", False)],
        (f"При температуре {low} °C скорость реакции была выше, чем при температуре {other} °C.", rates[temperatures.index(low)] > rates[temperatures.index(other)]),
        (f"При повышении температуры от {first} до {second} °C скорость реакции постоянно возрастала.", rising),
        ("Скорость реакции не зависит от температуры.", False),
        (f"При температуре выше {peak} °C скорость реакции снижалась.", True),
        ("Чем выше температура, тем выше скорость реакции во всём изученном диапазоне.", False),
        (f"При температуре {temperatures[0]} °C скорость реакции была ниже, чем при температуре {peak} °C.", True),
    ]
    for _ in range(300):
        items = [r.choice(item) if isinstance(item, list) else item for item in pool]
        picked = r.sample(items, 5)
        if sum(1 for _, flag in picked if flag) == 2:
            break
    else:
        return b21_data(r)
