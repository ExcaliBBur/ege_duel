# Приёмы, которые легко спутать: в одном задании из такой группы встречается только один.
DEVICE_CONFLICTS = [{"метафора", "эпитет", "олицетворение"}, {"анафора", "парцелляция"}, {"градация", "ряд однородных членов"},
                    {"гипербола", "литота"}, {"риторический вопрос", "диалог"}]


def conflicts(first, second):
    return any(first in group and second in group for group in DEVICE_CONFLICTS)


def o22_devices(r):
    names = sorted(DEVICES)
    while True:
        asked = r.sample(names, 5)
        if any(conflicts(a, b) for a in asked for b in asked if a != b):
            continue
        spare = [name for name in names if name not in asked and not any(conflicts(name, a) for a in asked)]
        if len(spare) >= 4:
            break
    options = asked + r.sample(spare, 4)
    r.shuffle(options)
    examples = [r.choice(DEVICES[name]) for name in asked]
    made = matching(
        "Установите соответствие между примерами и языковыми средствами выразительности, которые в них использованы: к каждой позиции первого столбца подберите "
        "соответствующую позицию из второго столбца.",
        examples, options, "".join(str(options.index(name) + 1) for name in asked),
        "; ".join(f"«{example}»: {name}" for example, name in zip(examples, asked)) + ".")
    return made


