def exact(text, answers, explanation):
    made = task(text, answers[0], explanation)
    made["answers"] = list(answers)
    made["kind"] = "exact"
    return made


def digits_set(text, numbers, explanation):
    made = task(text, "".join(str(n) for n in sorted(numbers)), explanation)
    made["kind"] = "set"
    return made


def numbered(options):
    return "\n".join(f"{index}) {option}" for index, option in enumerate(options, start=1))


