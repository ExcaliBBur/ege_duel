def e_rails(r):
    for _ in range(200):
        field = r.choice([Fraction(1, 5), Fraction(2, 5), Fraction(1, 2), 1])
        length = r.choice([Fraction(1, 5), Fraction(1, 2), 1])
        speed = r.choice([2, 4, 5, 10])
        resistance = r.choice([Fraction(1, 2), 1, 2, 4, 5])
        emf = Fraction(field) * length * speed
        current = emf / resistance
        if current.denominator in (1, 2, 4, 5, 10, 20, 25):
            break
    ask_power = r.random() < 0.5
    power = emf * current
    return task(
        f"Проводящая перемычка длиной {dec(length)} м скользит со скоростью {speed} м/с по горизонтальным рельсам, замкнутым на резистор сопротивлением "
        f"{dec(resistance)} Ом. Система находится в однородном вертикальном магнитном поле с индукцией {dec(field)} Тл. Сопротивлением рельсов и перемычки пренебрегите. "
        + ("Какая тепловая мощность выделяется на резисторе? Ответ дайте в ваттах." if ask_power else "Найдите силу тока в цепи. Ответ дайте в амперах."),
        dec(power if ask_power else current),
        f"ЭДС индукции ε = Bℓv = {dec(field)}·{dec(length)}·{speed} = {dec(emf)} В. Сила тока I = ε : R = {dec(current)} А."
        + (f" Мощность P = εI = {dec(power)} Вт." if ask_power else ""),
    )


def e_lens(r):
    for _ in range(200):
        focus = r.choice([10, 12, 15, 20, 30])
        magnification = Fraction(r.choice([Fraction(1, 2), 2, 3, 4, Fraction(1, 3)]))
        distance = focus * (1 + 1 / magnification)
        image = distance * magnification
        if is_finite_decimal(distance) and is_finite_decimal(image):
            break
    ask_image = r.random() < 0.5
    return task(
        f"Предмет расположен на расстоянии {dec(distance)} см от тонкой собирающей линзы с фокусным расстоянием {focus} см, перпендикулярно главной оптической оси. "
        + ("На каком расстоянии от линзы находится изображение предмета? Ответ дайте в сантиметрах." if ask_image
           else "Найдите увеличение, которое даёт линза. Ответ запишите десятичной дробью или целым числом, округлив до сотых."),
        dec(image) if ask_image else dec(round_half_up(magnification, 2)),
        f"По формуле тонкой линзы 1/F = 1/d + 1/f: f = dF : (d - F) = {dec(distance)}·{focus} : {dec(distance - focus)} = {dec(image)} см. "
        f"Увеличение Γ = f : d {'=' if round_half_up(magnification, 2) == magnification else '≈'} {dec(round_half_up(magnification, 2))}.",
    )


