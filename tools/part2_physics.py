def m_friction(r):
    mass = r.choice([2, 4, 5, 8, 10])
    mu = r.choice([Fraction(1, 10), Fraction(1, 5), Fraction(1, 4), Fraction(2, 5)])
    acceleration = r.choice([Fraction(1, 2), 1, Fraction(3, 2), 2, 3])
    force = mass * (acceleration + mu * G)
    return task(
        f"Брусок массой {mass} кг движется по горизонтальной поверхности под действием горизонтальной силы {dec(force)} Н. "
        f"Коэффициент трения между бруском и поверхностью равен {dec(mu)}. Найдите ускорение бруска. Ответ дайте в м/с². Ускорение свободного падения 10 м/с².",
        dec(acceleration),
        f"Сила трения равна μmg = {dec(mu)}·{mass}·10 = {dec(mu * mass * G)} Н. По второму закону Ньютона a = (F - Fтр) : m = "
        f"({dec(force)} - {dec(mu * mass * G)}) : {mass} = {dec(acceleration)} м/с².",
    )


def m_energy_height(r):
    speed = r.choice([10, 20, 30, 40])
    part = r.choice([(1, "равна его потенциальной энергии", 2), (3, "в 3 раза больше его потенциальной энергии", 4)])
    ratio, wording, divisor = part
    height = Fraction(speed * speed, 2 * G * divisor)
    return task(
        f"Тело брошено вертикально вверх с поверхности земли со скоростью {speed} м/с. На какой высоте кинетическая энергия тела {wording}? "
        "Потенциальную энергию отсчитывайте от поверхности земли, сопротивлением воздуха пренебрегите. Ответ дайте в метрах. Ускорение свободного падения 10 м/с².",
        dec(height),
        f"По закону сохранения энергии mv²/2 = Eк + mgh. По условию Eк = {'' if ratio == 1 else ratio}mgh, поэтому mv²/2 = {divisor}mgh и h = v² : ({2 * divisor}g) = "
        f"{speed}² : {2 * divisor * G} = {dec(height)} м.",
    )


