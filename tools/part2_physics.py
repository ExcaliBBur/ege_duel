PENDULUMS = [(Fraction(1, 5), 2), (Fraction(9, 20), 3), (Fraction(4, 5), 4), (Fraction(5, 4), 5), (Fraction(9, 5), 6), (Fraction(16, 5), 8)]  # длина нити и скорость внизу


def c_pendulum_hit(r):
    for _ in range(200):
        length, speed = r.choice(PENDULUMS)
        ball, block = r.choice([(1, 1), (1, 3), (1, 2), (2, 1), (1, 4), (3, 1), (1, 5), (2, 2)])
        common = Fraction(ball * speed, ball + block)
        height = common * common / (2 * G) * 100  # в сантиметрах
        if height.denominator in (1, 2, 4, 5):
            break
    return task(
        f"Пластилиновый шарик массой {ball * 100} г подвешен на нити длиной {dec(length)} м. Нить отклонили до горизонтального положения и отпустили без начальной скорости. "
        f"В нижней точке шарик ударяется о такой же по размерам неподвижный пластилиновый шарик массой {block * 100} г, висящий на нити той же длины, и слипается с ним. "
        "На какую высоту поднимутся шарики после удара? Ответ дайте в сантиметрах. Ускорение свободного падения 10 м/с², сопротивлением воздуха пренебрегите.",
        dec(height),
        f"До удара сохраняется механическая энергия (сила натяжения работы не совершает): v = √(2gL) = {speed} м/с. При ударе сохраняется импульс системы "
        f"(удар кратковременный, внешние силы вертикальны): u = {ball * 100}·{speed} : {(ball + block) * 100} = "
        f"{frac(common)} м/с. "
        f"После удара снова сохраняется энергия: h = u² : (2g) = {dec(height)} см.",
    )


