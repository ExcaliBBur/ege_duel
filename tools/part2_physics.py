def t_full_circuit(r):
    internal = r.choice([1, 2])
    external = r.choice([2, 3, 4, 5, 8, 10])
    current = r.choice([1, 2, 3])
    emf = current * (internal + external)
    ask_power = r.random() < 0.6
    answer = current * current * external if ask_power else current * external
    return task(
        f"К источнику тока с ЭДС {emf} В и внутренним сопротивлением {internal} Ом подключён резистор сопротивлением {external} Ом. "
        + ("Какая мощность выделяется на резисторе? Ответ дайте в ваттах." if ask_power else "Найдите напряжение на резисторе. Ответ дайте в вольтах."),
        dec(answer),
        f"По закону Ома для полной цепи I = ε : (R + r) = {emf} : {internal + external} = {current} А. "
        + (f"Мощность P = I²R = {current}²·{external} = {answer} Вт." if ask_power else f"Напряжение U = IR = {current}·{external} = {answer} В."),
    )


