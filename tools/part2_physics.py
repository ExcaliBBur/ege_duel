def g_two_vessels(r):
    for _ in range(200):
        v1, v2 = r.choice([1, 2, 3, 4, 5, 6]), r.choice([1, 2, 3, 4, 6])
        p1, p2 = r.choice([100, 150, 200, 300, 400, 500]), r.choice([100, 200, 250, 300, 600])
        total = Fraction(p1 * v1 + p2 * v2, v1 + v2)
        if p1 != p2 and total.denominator == 1:
            break
    return task(
        f"Два сосуда объёмами {v1} л и {v2} л содержат один и тот же идеальный газ при одинаковой температуре. Давление в первом сосуде {p1} кПа, во втором {p2} кПа. "
        "Сосуды соединяют тонкой трубкой. Какое давление установится в сосудах, если температура не изменяется? Ответ дайте в килопаскалях.",
        dec(total),
        f"Количество вещества сохраняется: p₁V₁ + p₂V₂ = p(V₁ + V₂). p = ({p1}·{v1} + {p2}·{v2}) : ({v1} + {v2}) = {dec(total)} кПа.",
    )


def g_cycle(r):
    for _ in range(200):
        k, n = r.choice([2, 3, 4]), r.choice([2, 3, 4, 5])
        efficiency = Fraction((k - 1) * (n - 1) * 100) / (Fraction(3, 2) * (k - 1) + Fraction(5, 2) * k * (n - 1))
        shift = efficiency - int(efficiency)
        if abs(shift - Fraction(1, 2)) > Fraction(1, 20):
            break
    answer = round_half_up(efficiency, 0)
    return task(
        f"Одноатомный идеальный газ совершает цикл, состоящий из двух изохор и двух изобар. В цикле давление газа изменяется от p₀ до {k}p₀, а объём от V₀ до {n}V₀. "
        "Найдите КПД цикла. Ответ дайте в процентах, округлив до целого числа.",
        dec(answer),
        f"Работа за цикл равна площади прямоугольника: A = {(k - 1) * (n - 1)}p₀V₀. Газ получает тепло при изохорном нагревании (3/2·{k - 1}p₀V₀) и при изобарном "
        f"расширении (5/2·{k}p₀·{n - 1}V₀): Q = {dec(Fraction(3, 2) * (k - 1) + Fraction(5, 2) * k * (n - 1))}p₀V₀. КПД = A : Q ≈ {dec(answer)}%.",
    )


