    work, characters = r.choice(CHARACTERS)
    picked = r.sample(characters, 4)
    asked = picked[:3]
    options = [description for _, description in picked]
    r.shuffle(options)
    return matching(
        f"Установите соответствие между персонажами {work} и их характеристиками: к каждой позиции первого столбца подберите соответствующую позицию из второго столбца.",
        [name for name, _ in asked], options, "".join(str(options.index(description) + 1) for _, description in asked),
        "; ".join(f"{name}: {description}" for name, description in asked) + ".")


