def e_deposit(r):
    start = r.choice([100, 200, 300, 400, 500])
    extra = r.choice([100, 200, 300])
    rate = r.choice([10, 20])
    q = Fraction(100 + rate, 100)
    result = ((start * q + extra) * q + extra) * q
    return task(
        f"Вкладчик положил в банк {start} тыс. рублей под {rate}% годовых. Проценты начисляются в конце каждого года на всю сумму вклада. "
        f"В конце первого и в конце второго года, сразу после начисления процентов, вкладчик добавлял на счёт по {extra} тыс. рублей. "
        "Сколько тысяч рублей окажется на счёте в конце третьего года после начисления процентов?",
        dec(result),
        f"Конец первого года: {start}·{dec(q)} + {extra} = {dec(start * q + extra)}. Конец второго: {dec(start * q + extra)}·{dec(q)} + {extra} = "
        f"{dec((start * q + extra) * q + extra)}. Конец третьего: {dec((start * q + extra) * q + extra)}·{dec(q)} = {dec(result)} тыс. рублей.",
    )


