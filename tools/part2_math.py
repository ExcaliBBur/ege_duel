def p_inradius(r):
    k = r.choice([5, 10, 15, 20, 25])
    a, b, c = 3 * k, 4 * k, 5 * k
    radius = Fraction(a + b - c, 2)
    side, name = r.choice([(a, "BCH"), (b, "ACH")])
    answer = radius * side / c
    return task(
        f"В прямоугольном треугольнике ABC с прямым углом C катеты BC = {a} и AC = {b}. Из вершины C проведена высота CH. "
        f"Найдите радиус окружности, вписанной в треугольник {name}.",
        dec(answer),
        f"Гипотенуза AB = {c}, радиус окружности, вписанной в ABC, равен ({a} + {b} - {c}) : 2 = {dec(radius)}. Треугольник {name} подобен треугольнику ABC "
        f"(его гипотенуза равна {side}) с коэффициентом {side} : {c}, поэтому искомый радиус равен {dec(radius)}·{side} : {c} = {dec(answer)}.",
    )


def p_trapezoid(r):
    small = r.randint(2, 6)
    big = small + r.randint(1, 6)
    factor = r.randint(1, 4)
    area_small = small * small * factor
    answer = factor * (small + big) ** 2
    return task(
        f"Диагонали трапеции ABCD с основаниями AD = {big} и BC = {small} пересекаются в точке O. Площадь треугольника BOC равна {area_small}. Найдите площадь трапеции.",
        dec(answer),
        f"Треугольники BOC и DOA подобны с коэффициентом {small} : {big}, поэтому площадь AOD равна {area_small}·{big}² : {small}² = {factor * big * big}. "
        f"Треугольники AOB и COD равновелики, площадь каждого равна {area_small}·{big} : {small} = {factor * small * big}. "
        f"Площадь трапеции: {area_small} + {factor * big * big} + 2·{factor * small * big} = {answer}.",
    )


def p_tangent(r):
    m, n = r.sample([1, 2, 3, 4, 5], 2)
    k = r.choice([1, 2, 3])
    big, small = max(m, n) ** 2 * k, min(m, n) ** 2 * k
    answer = 2 * m * n * k
    return task(
        f"Две окружности радиусов {big} и {small} касаются внешним образом. К ним проведена общая внешняя касательная, A и B точки касания. Найдите длину отрезка AB.",
        dec(answer),
        f"Расстояние между центрами равно {big} + {small} = {big + small}. Проведём через центр меньшей окружности прямую, параллельную AB: получится прямоугольный "
        f"треугольник с гипотенузой {big + small} и катетом {big} - {small} = {big - small}. AB = √({big + small}² - {big - small}²) = 2√({big}·{small}) = {answer}.",
    )


