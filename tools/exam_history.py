def h4_table(r):
    rows = r.sample(TRIPLES, 5)
    shown, spare = rows[:3], rows[3:]
    letters = iter("АБВГДЕ")
    answers, lines = [], []
    for event, date, person in shown:
        hidden = r.sample(range(3), 2)
        cells = []
        for index, (label, value) in enumerate((("событие", event), ("дата", date), ("участник", person))):
            if index in hidden:
                answers.append(value)
                cells.append(f"{label}: ({next(letters)})")
            else:
                cells.append(f"{label}: {value}")
        lines.append("; ".join(cells))
    options = answers + r.sample([value for row in spare for value in row], 3)
    r.shuffle(options)
    made = task(
        "Заполните пропуски в строках таблицы, используя приведённый ниже список пропущенных элементов: для каждого пропуска, обозначенного буквой, выберите номер нужного элемента. "
        "Запишите цифры в порядке букв АБВГДЕ, без пробелов.\n\n" + "\n".join(f"Строка {index}: {line}" for index, line in enumerate(lines, start=1))
        + "\n\nПропущенные элементы:\n" + "\n".join(f"{index}) {option}" for index, option in enumerate(options, start=1)),
        "".join(str(options.index(answer) + 1) for answer in answers),
        "; ".join(f"{event}, {date}, {person}" for event, date, person in shown) + ".")
    made["kind"] = "order"
    return made


