def groups_matching(r, intro, groups):
    """Соответствие: четыре позиции слева, шесть справа (две лишние). groups: список (позиция, варианты)."""
    asked = r.sample(groups, 4)
    answers = [r.choice(options) for _, options in asked]
    names = {name for name, _ in asked}
    spare = [option for name, options in groups if name not in names for option in options]
    right = answers + r.sample(spare, 2)
    r.shuffle(right)
    return matching(intro, [name for name, _ in asked], right, "".join(str(right.index(answer) + 1) for answer in answers),
                    "; ".join(f"{name}: {answer}" for (name, _), answer in zip(asked, answers)) + ".")


