"""Задания гуманитарных предметов, которые строятся по таблицам фактов.

Каждая таблица это список проверяемых фактов (дата события, столица страны, автор произведения,
верное ударение). Генератор берёт случайный факт и оформляет его как задание. Поле key у задания
называет использованный факт: сборка банка берёт каждый факт не больше одного раза на генератор.

При импорте модуль добавляет свои генераторы в generators.GENERATED.
"""

