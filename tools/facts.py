    sentence, correct, wrong, why = r.choice(PARONYMS)
    options = [correct] + wrong
    r.shuffle(options)
    lines = "\n".join(f"{number}) {option}" for number, option in enumerate(options, start=1))
    return fact(
        sentence,
        f"Какое слово нужно вставить на место пропуска? Запишите номер ответа.\n\n{sentence}\n{lines}",
        str(options.index(correct) + 1),
        why,
    )


