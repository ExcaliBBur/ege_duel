def terms(r, table, name, question="Что называют словом «{term}»?", reverse_question="Какой термин соответствует определению: «{definition}»?"):
    """Задание на термин: по определению выбрать слово или по слову выбрать определение."""
    term, definition = r.choice(table)
    if r.random() < 0.5:
        made = choice(r, term, reverse_question.format(definition=definition), term, [item for item, _ in table], f"Это {term}.")
        made["key"] = f"{name}:{term}:слово"
    else:
        made = choice(
            r, term, question.format(term=term), definition, [item for _, item in table], f"{term.capitalize()}: {definition}."
        )
        made["key"] = f"{name}:{term}:определение"
    return made


