    r.shuffle(options)
    lines = "\n".join(f"{number}) {option}" for number, option in enumerate(options, start=1))
    answer = "".join(str(number) for number, option in enumerate(options, start=1) if option in right)
    return fact(
        name + "|" + "|".join(sorted(options)),
        f"Что из перечисленного относится к {name}? Запишите номера без пробелов.\n{lines}",
        answer,
        "Подходят: " + ", ".join(sorted(right)) + ".",
        kind="set",
        points=2,
    )


