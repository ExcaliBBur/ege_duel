def rus_stress(r):
    picked = r.sample(STRESS, 4)
    target = picked[0]
    if r.random() < 0.5:
        options = [target[0]] + [wrong for _, wrong in picked[1:]]
        question = "Ударная гласная записана заглавной буквой. В каком слове ударение поставлено верно?"
        correct = target[0]
        how = f"Верно: {target[0]}. В остальных словах правильно так: " + ", ".join(right for right, _ in picked[1:]) + "."
    else:
        options = [target[1]] + [right for right, _ in picked[1:]]
        question = "Ударная гласная записана заглавной буквой. В каком слове ударение поставлено неверно?"
        correct = target[1]
        how = f"Ошибка в слове «{target[1]}», правильно: {target[0]}."
    r.shuffle(options)
    lines = "\n".join(f"{number}) {option}" for number, option in enumerate(options, start=1))
    return fact(target[0], f"{question} Запишите номер ответа.\n{lines}", str(options.index(correct) + 1), how)


