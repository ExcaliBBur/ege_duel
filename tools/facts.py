LETTER_PAIRS = {"а": "о", "о": "а", "е": "и", "и": "е", "н": "нн", "нн": "н"}


def spelling(r, table, name, how_to_ask):
    """Одно слово с нужной буквой и три слова с парной буквой."""
    word, letter = r.choice(table)
    other = LETTER_PAIRS[letter]
    wrong = [item for item, item_letter in table if item_letter == other]
    shown = letter.upper()
    made = choice(
        r,
        word,
        how_to_ask.format(letter=shown),
        word,
        wrong,
        f"В слове «{word.replace('..', letter)}» пишется {shown}. В остальных словах пишется {other.upper()}.",
    )
    made["key"] = f"{name}:{word}"
    return made


