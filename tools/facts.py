def bio_gametes(r):
    letters = r.sample(["A", "B", "C", "D"], r.choice([2, 3]))
    genotype, hetero = "", 0
    for letter in sorted(letters):
        kind = r.choice(["AA", "Aa", "aa"])
        if kind == "Aa":
            hetero += 1
        genotype += {"AA": letter + letter, "Aa": letter + letter.lower(), "aa": letter.lower() * 2}[kind]
    return fact(
        genotype,
        f"Сколько типов гамет образует организм с генотипом {genotype} при независимом наследовании генов?",
        str(2 ** hetero),
        f"Гетерозиготных пар генов: {hetero}. Число типов гамет равно 2 в степени {hetero}, то есть {2 ** hetero}.",
        kind="number",
    )


