def fact(key, text, answer, explanation, kind="exact", points=1, answers=None):
    made = {"key": str(key), "text": text, "answer": answer, "explanation": explanation, "kind": kind, "points": points}
    if answers:
        made["answers"] = answers
    return made


def choice(r, key, question, correct, wrong, explanation, count=4):
    """Задание с выбором одного ответа: правильный вариант и случайные неверные из списка wrong."""
    wrong = [item for item in dict.fromkeys(wrong) if item != correct]
    options = [correct] + r.sample(wrong, min(count - 1, len(wrong)))
    r.shuffle(options)
    lines = "\n".join(f"{number}) {option}" for number, option in enumerate(options, start=1))
    return fact(key, f"{question} Запишите номер ответа.\n{lines}", str(options.index(correct) + 1), explanation)


