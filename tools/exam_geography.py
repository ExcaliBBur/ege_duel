def numbered(options):
    return "\n".join(f"{index}) {option}" for index, option in enumerate(options, start=1))


def ordering(r, text, items, explanation):
    """Расположить объекты в нужном порядке. items уже стоят в правильном порядке."""
    shown = items[:]
    while shown == items:
        r.shuffle(shown)
    made = task(f"{text} Запишите получившуюся последовательность цифр.\n\n{numbered(shown)}", "".join(str(shown.index(item) + 1) for item in items), explanation)
    made["kind"] = "order"
    return made


def spaced(number) -> str:
    return f"{number:,}".replace(",", " ")


