def g1_meridian(r):
    first, second = sorted(r.sample(range(40, 76, 2), 2))
    return task(
        f"Определите расстояние между двумя пунктами, расположенными на одном меридиане: один на {first}° с. ш., другой на {second}° с. ш. "
        "Длина дуги меридиана в 1° равна 111 км. Ответ дайте в километрах.",
        dec((second - first) * 111), f"Разность широт {second - first}°: {second - first} · 111 = {(second - first) * 111} км.")


def g1_named_scale(r):
    scale = r.choice([5000, 10000, 25000, 50000, 100000, 200000, 500000, 1000000])
    metres = scale // 100
    if r.random() < 0.5:
        return task(f"Масштаб карты 1 : {spaced(scale)}. Сколько метров на местности соответствует 1 см на карте?", dec(metres),
                    f"1 см на карте соответствует {spaced(scale)} см на местности, то есть {spaced(metres)} м.")
    length = r.choice([2, 4, 5, 8, 10, 12, 15])
    return task(f"На плане местности в 1 см {spaced(metres)} м. Какой длины на плане будет отрезок, соответствующий расстоянию {spaced(metres * length)} м на местности? Ответ дайте в сантиметрах.",
                dec(length), f"{spaced(metres * length)} : {spaced(metres)} = {length} см.")


